CREATE TABLE IF NOT EXISTS sweepstake_pots (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 race_year SMALLINT UNSIGNED NOT NULL,
 entry_cents INT UNSIGNED NOT NULL,
 first_pct TINYINT UNSIGNED NOT NULL DEFAULT 60,
 second_pct TINYINT UNSIGNED NOT NULL DEFAULT 25,
 third_pct TINYINT UNSIGNED NOT NULL DEFAULT 15,
 status VARCHAR(12) NOT NULL DEFAULT 'open',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sweepstake_runners (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 pot_id INT UNSIGNED NOT NULL,
 number SMALLINT UNSIGNED NOT NULL,
 name VARCHAR(100) NOT NULL,
 placing TINYINT UNSIGNED NULL,
 UNIQUE KEY runner_number (pot_id, number),
 UNIQUE KEY runner_placing (pot_id, placing),
 FOREIGN KEY (pot_id) REFERENCES sweepstake_pots(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sweepstake_entries (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 pot_id INT UNSIGNED NOT NULL,
 participant VARCHAR(100) NOT NULL,
 paid TINYINT UNSIGNED NOT NULL DEFAULT 0,
 runner_id INT UNSIGNED NULL,
 UNIQUE KEY assigned_runner (runner_id),
 FOREIGN KEY (pot_id) REFERENCES sweepstake_pots(id) ON DELETE CASCADE,
 FOREIGN KEY (runner_id) REFERENCES sweepstake_runners(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
